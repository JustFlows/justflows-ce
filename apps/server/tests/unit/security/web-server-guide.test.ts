import os from "node:os";
import path from "node:path";
import { mkdtemp, writeFile } from "node:fs/promises";
import { describe, expect, it } from "vitest";
import {
  buildWebServerGuide,
  readRootHtaccessState,
  renderNginxUploads,
} from "../../../src/lib/security/web-server-guide.js";

const HTACCESS = "# Generated by Justflows — site-root hardening.\nOptions -Indexes\n";

describe("buildWebServerGuide", () => {
  it("hides files from a site that is not the installation", () => {
    const guide = buildWebServerGuide({
      installationRoot: false,
      htaccess: "current",
      port: "3000",
      uploadsDir: "/var/www/uploads",
      accelPrefix: undefined,
      htaccessBody: HTACCESS,
    });
    expect(guide.installationRoot).toBe(false);
    expect(guide.environments).toEqual([]);
  });

  it("gives nginx a proxy for uploads and an internal alias for the handoff", () => {
    const guide = buildWebServerGuide({
      installationRoot: true,
      htaccess: "current",
      port: "4000",
      uploadsDir: "/var/www/app/uploads",
      accelPrefix: undefined,
      htaccessBody: HTACCESS,
    });
    const nginx = guide.environments.find((item) => item.id === "nginx")?.config ?? "";
    const uploads = nginx.split("location /internal-uploads/")[0] ?? "";
    expect(uploads).toContain("location /uploads/");
    expect(uploads).toContain("proxy_pass http://127.0.0.1:4000;");
    expect(uploads).not.toMatch(/^\s*alias\s/m);
    expect(nginx).toContain("location /internal-uploads/");
    expect(nginx).toContain("internal;");
    expect(nginx).toContain("alias /var/www/app/uploads/;");
    expect(guide.environments.find((item) => item.id === "apache")?.config).toBe(HTACCESS);
    expect(guide.environments.find((item) => item.id === "passenger")?.config).toBeNull();
    expect(guide.environments.find((item) => item.id === "apache")?.automatic).toBe(true);
    expect(guide.environments.find((item) => item.id === "nginx")?.automatic).toBe(false);
  });

  it("omits the internal alias when the uploads path cannot be pasted", () => {
    const nginx = renderNginxUploads("3000", null, "/internal-uploads");
    expect(nginx).not.toMatch(/^\s*alias\s/m);
    expect(nginx).toContain("could not be written");
  });

  it("reads whether the managed htaccess is current, pending, custom, or missing", async () => {
    const dir = await mkdtemp(path.join(os.tmpdir(), "jf-htaccess-"));
    expect(await readRootHtaccessState(dir, HTACCESS)).toBe("missing");
    await writeFile(path.join(dir, ".htaccess"), HTACCESS);
    expect(await readRootHtaccessState(dir, HTACCESS)).toBe("current");
    await writeFile(path.join(dir, ".htaccess"), `${HTACCESS}# extra\n`);
    expect(await readRootHtaccessState(dir, HTACCESS)).toBe("pending");
    await writeFile(path.join(dir, ".htaccess"), "# hand edited\n");
    expect(await readRootHtaccessState(dir, HTACCESS)).toBe("custom");
  });
});
